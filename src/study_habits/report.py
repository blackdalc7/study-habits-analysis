"""Run the whole pipeline: simulate -> make messy -> clean -> analyse -> charts + report.

    python -m study_habits                 # writes data/, docs/charts/ and docs/REPORT.md
    python -m study_habits --students 1000 --seed 1
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from study_habits import analysis, charts
from study_habits.clean import clean
from study_habits.simulate import make_messy, simulate


def build_report(df: pd.DataFrame, log_md: str) -> str:
    """Build the Markdown report: cleaning log, statistics, group comparisons and the model."""
    fit = analysis.linear_model(df)
    coef = fit.as_series()
    lines = [
        "# Report: study habits vs exam scores",
        "",
        "_Generated by `python -m study_habits`. All data is simulated, see the README._",
        "",
        f"**{len(df)} students** after cleaning.",
        "",
        "## Cleaning log",
        "",
        log_md,
        "",
        "## Summary statistics",
        "",
        analysis.summary(df).to_markdown(),
        "",
        "## Correlation with exam score",
        "",
        analysis.correlations(df)["exam_score"].drop("exam_score")
        .sort_values(ascending=False).to_frame("r").to_markdown(),
        "",
        "## Average score by hours of sleep",
        "",
        analysis.score_by_sleep(df).to_markdown(),
        "",
        "## Average score by cups of coffee",
        "",
        analysis.score_by_coffee(df).to_markdown(),
        "",
        "## By major",
        "",
        analysis.score_by_major(df).to_markdown(),
        "",
        "## Part-time job vs no job",
        "",
        analysis.job_vs_no_job(df).to_markdown(),
        "",
        "## Linear model",
        "",
        f"`exam_score ~ {' + '.join(fit.names)}`, fitted with `numpy.linalg.lstsq`.",
        "",
        coef.to_frame("points per unit").to_markdown(),
        "",
        f"Intercept {fit.intercept:.1f}, **R² = {fit.r_squared:.2f}**.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="study_habits")
    parser.add_argument("--students", type=int, default=400)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--docs-dir", type=Path, default=Path("docs"))
    args = parser.parse_args(argv)

    args.data_dir.mkdir(parents=True, exist_ok=True)
    raw = make_messy(simulate(args.students, args.seed))
    raw.to_csv(args.data_dir / "survey_raw.csv", index=False)

    df, log = clean(pd.read_csv(args.data_dir / "survey_raw.csv"))
    df.to_csv(args.data_dir / "survey_clean.csv", index=False)

    paths = charts.save_all(df, args.docs_dir / "charts")
    report = args.docs_dir / "REPORT.md"
    report.write_text(build_report(df, log.as_markdown()), encoding="utf-8")

    print(f"raw rows     : {len(raw)}")
    print(f"clean rows   : {len(df)}")
    print(f"best sleep   : {analysis.best_sleep_bucket(df)} hours")
    print(f"model R²     : {analysis.linear_model(df).r_squared:.2f}")
    print(f"charts       : {', '.join(p.name for p in paths)}")
    print(f"report       : {report}")
    return 0
